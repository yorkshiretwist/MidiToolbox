// The firmware-facing files: a generated C++ header (for builds that compile the
// unit's wiring in) and a build guide. The runtime equivalent of the header is
// deviceProfile.ts, which writes the device.json the firmware reads from the SD card.

import type { Design } from '../../types/device'
import type { Analysis } from '../checks'
import { buttonDiameter, screenDims } from '../geometry'
import { performanceButtons } from '../layout'
import { MEASURE_HEADLINE, RISK_WARNING, measureWarning } from './notices'
import { cString } from './xml'

/**
 * The on-screen grid as rows of button ids. A cell's id sits in the half-column
 * it starts in; the half-column after it (which the cell also covers) is left
 * at 255.
 */
export function gridCellRows(design: Design, analysis: Analysis): number[][] {
  const { grid } = analysis
  const perf = performanceButtons(design)
  return Array.from({ length: grid.rows }, (_, row) =>
    Array.from({ length: grid.halfCols }, (_, halfCol) => {
      const cell = grid.cells.find((c) => c.row === row && c.halfCol === halfCol)
      const hit = cell && perf.find((b) => b.uid === cell.uid)
      return hit ? hit.id : 255
    }),
  )
}

export function firmwareHeader(design: Design, analysis: Analysis): string {
  const { plan, screen, mcu, grid } = analysis
  const byId = [...design.buttons].sort((a, b) => a.id - b.id)
  const idOf = new Map(design.buttons.map((b) => [b.uid, b.id]))
  const dims = screenDims(screen, design.screen.orientation)
  const pins = byId.map((b) => plan.buttonPins.get(b.uid) ?? -1)

  const cellRows = gridCellRows(design, analysis).map((row) => row.join(', '))

  // `padEnd` is a no-op once `name` reaches its target width, which drops the
  // separating space entirely for a name at or past 24 characters (e.g.
  // "SCREEN_DRIVER_ILI9341_T4" is exactly 24) and pastes the value straight
  // onto the name - `#define SCREEN_DRIVER_ILI9341_T41`, silently wrong.
  // Padding the name-plus-a-space instead guarantees at least one separator
  // no matter how long the name is.
  const pad = (name: string) => `#define ${`${name} `.padEnd(25)}`
  const lines: string[] = [
    '// Generated by MIDI Toolbox Designer. Do not edit by hand.',
    `// Unit: ${design.name.replaceAll('\n', ' ')} (${design.unit.width} x ${design.unit.height} mm, ${design.purpose} control)`,
    '',
    '#ifndef MidiToolboxDevice_h',
    '#define MidiToolboxDevice_h',
    '',
    '#include <stdint.h>',
    '',
    `${pad('DEVICE_NAME')}"${cString(design.name)}"`,
    `${pad('MICROCONTROLLER')}"${mcu.name}"`,
    '',
    '// Buttons: the array index is the button id that performance configs use.',
    `${pad('BUTTON_COUNT')}${design.buttons.length}`,
    `${pad('NAV_SELECT_ID')}${idOf.get(design.nav.select)}`,
    `${pad('NAV_DOWN_ID')}${idOf.get(design.nav.down)}`,
    `${pad('NAV_UP_ID')}${idOf.get(design.nav.up)}`,
    `static const int8_t BUTTON_PINS[BUTTON_COUNT] = { ${pins.join(', ')} };`,
    '',
    '// Screen',
    `${pad(`SCREEN_DRIVER_${screen.driver.toUpperCase()}`)}1`,
    `${pad('SCREEN_LX')}${dims.resolution[0]}`,
    `${pad('SCREEN_LY')}${dims.resolution[1]}`,
    `${pad(`SCREEN_ORIENTATION_${design.screen.orientation.toUpperCase()}`)}1`,
    `${pad('SCREEN_HAS_TOUCH')}${screen.touch.type === 'none' ? 0 : 1}`,
    ...(screen.touch.controller ? [`${pad(`SCREEN_TOUCH_${screen.touch.controller.toUpperCase()}`)}1`] : []),
    ...plan.screenPins.map((p) => `${pad(`SCREEN_PIN_${p.role.toUpperCase()}`)}${p.pin}`),
    '',
    '// The on-screen grid mirrors the performance buttons. Columns are half a cell wide:',
    '// a button\'s id sits in the half-column its cell starts in, and the cell covers that',
    '// half-column and the next, so a row offset by half a cell is a row shifted one',
    '// half-column. 255 marks a half-column where no cell starts.',
    `${pad('SCREEN_GRID_HALF_COLS')}${grid.halfCols}`,
    `${pad('SCREEN_GRID_ROWS')}${grid.rows}`,
    `static const uint8_t SCREEN_GRID_BUTTON_IDS[SCREEN_GRID_ROWS][SCREEN_GRID_HALF_COLS] = {`,
    ...cellRows.map((row) => `  { ${row} },`),
    '};',
    '',
    '// RGB LEDs, driven through a chain of 74HC595 shift registers (ShiftPWM)',
    `${pad('LED_PIN_LATCH')}${plan.ledPins.latch}`,
    `${pad('LED_PIN_DATA')}${plan.ledPins.data}`,
    `${pad('LED_PIN_CLOCK')}${plan.ledPins.clock}`,
    `${pad('SHIFT_REGISTERS')}${plan.registers}`,
    '',
    '// Config storage',
    `${pad('SD_BUILTIN')}${mcu.sdBuiltIn ? 1 : 0}`,
    ...plan.sdPins.map((p) => `${pad(`SD_PIN_${p.role.replace(/^SD_/, '')}`)}${p.pin}`),
    '',
    '#endif',
    '',
  ]
  return lines.join('\n')
}

export function buildGuide(design: Design, analysis: Analysis): string {
  const { screen, mcu } = analysis
  const untested = screen.status === 'untested'
  const dims = screenDims(screen, design.screen.orientation)
  return [
    `# Build guide — ${design.name}`,
    '',
    `## ⚠ ${MEASURE_HEADLINE}`,
    '',
    measureWarning(buttonDiameter(design.purpose), dims.module),
    '',
    'Drilling and cutting cannot be undone. Before you make any hole:',
    '',
    '1. Measure each footswitch or button you actually bought (the body or thread diameter, and how thick the panel can be).',
    '2. Measure the screen module and its visible area, and note where the mounting holes are.',
    '3. Compare with the sizes on `drawing.svg` and correct the drawing if they differ.',
    '4. Try the layout on scrap material or cardboard before you cut the real panel.',
    '',
    '## ⚠ BUILD AT YOUR OWN RISK',
    '',
    RISK_WARNING,
    '',
    'This guide, the drawing, the schematic and the parts list are generated from your design and have not',
    'been tested on real hardware. Before you apply power for the first time:',
    '',
    '1. Compare every connection on `schematic.svg` with the datasheets of the parts you actually bought.',
    '2. With nothing plugged in, use a multimeter to check for shorts between power and ground, and that each',
    '   pin goes where the schematic says.',
    '3. Check the polarity of the LEDs, the regulator and any capacitors, and the supply voltage.',
    '4. Power up one stage at a time (the Teensy alone, then buttons, screen, LEDs).',
    '',
    'The firmware in `MIDI-Toolbox/` reads `MidiToolboxDevice.h` for its button count and pins, its',
    'screen and its LED wiring - copying yours in and recompiling is enough to build a unit around this',
    'design. It only ever implements the ILI9341 screen driver itself (see below if yours is a different',
    'controller), and only Teensy 4.1 - see the Designer app for why.',
    '',
    '## What you need',
    '',
    `- ${mcu.name} and a micro-USB cable.`,
    '- Arduino IDE with [Teensyduino](https://www.pjrc.com/teensy/td_download.html) installed.',
    '- Libraries the firmware includes: ArduinoJson, Bounce, ShiftPWM, LVGL and ' +
      (screen.driver === 'ILI9341_T4' ? '[ILI9341_T4](https://github.com/vindar/ILI9341_T4).' : `a driver for the ${screen.controller} (see below).`),
    '- SD and SPI come with Teensyduino.',
    '',
    '## Steps',
    '',
    '1. Build the hardware from `drawing.svg`, `schematic.svg` and `parts.csv`.',
    '2. Copy `MidiToolboxDevice.h` into the `MIDI-Toolbox/` sketch folder next to `MIDI-Toolbox.ino`.',
    `3. In the Arduino IDE choose **Tools → Board → Teensy 4.1** and **Tools → USB Type → Serial + MIDI**.`,
    '4. Compile and upload.',
    '5. Copy your performance configs (`.json`) to the SD card, in the config directory named in `ConfigStore.h`.',
    '',
    ...(untested
      ? [
          '## About the screen driver',
          '',
          `The firmware only has a working driver for the ILI9341 (\`ILI9341_T4\`). **${screen.name} is untested**: ` +
            `you will need to write a small driver adapter for the ${screen.controller} — initialise the panel, ` +
            'push LVGL\'s pixels to it, and read touch if it has any — then check the layout on the real screen.',
          '',
        ]
      : []),
    '## Checking the wiring',
    '',
    'The pin numbers in `MidiToolboxDevice.h` match `schematic.svg`. Press each footswitch with the serial monitor open:',
    'the firmware logs `Button N pressed` at debug level, where N is the button id (printed number minus one).',
    '',
  ].join('\n')
}
