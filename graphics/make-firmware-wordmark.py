"""Builds MIDI-Toolbox/Wordmark.h (the startup-screen wordmark) from a transparent PNG of the wordmark.

    python graphics/make-firmware-wordmark.py wordmark.png MIDI-Toolbox/Wordmark.h [width]

wordmark.png is graphics/wordmark.svg (the version without the dark background, as in
pages/wordmark.svg) rendered large with a transparent background, for example by a browser. The
image is cropped to its content, scaled to `width` pixels (default 288) and written as an LVGL
ARGB8888 image: 4 bytes per pixel in B, G, R, A order, straight (not premultiplied) alpha.
Needs Pillow (pip install pillow).
"""
import sys
from PIL import Image

src, dst = sys.argv[1], sys.argv[2]
width = int(sys.argv[3]) if len(sys.argv) > 3 else 288

im = Image.open(src).convert('RGBA')
box = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
im = im.crop(box)
height = round(im.height * width / im.width)
im = im.resize((width, height), Image.LANCZOS)

data = bytearray()
for r, g, b, a in im.getdata():
    data += bytes((b, g, r, a))

lines = []
for i in range(0, len(data), 24):
    lines.append('  ' + ', '.join(f'0x{x:02x}' for x in data[i:i + 24]) + ',')

with open(dst, 'w', newline='\n') as f:
    f.write(f'''// GENERATED by graphics/make-firmware-wordmark.py from graphics/wordmark.svg - do not edit by hand.
//
// The MIDI Toolbox wordmark for the startup screen, as an LVGL image: {width} x {height} px,
// ARGB8888 (B, G, R, A bytes, straight alpha). in its own .progmem section, so it lives in flash only - a plain
// const array on a Teensy 4 is copied into RAM1 as well, which the firmware cannot spare.
// Drawing it needs LV_USE_IMAGE set to 1 in lv_conf.h (Screen.h checks this).
#pragma once

#include <lvgl.h>

#define WORDMARK_IMG_W {width}
#define WORDMARK_IMG_H {height}

static const uint8_t WORDMARK_IMG_DATA[] __attribute__((section(".progmem.wordmark"))) = {{
''' + '\n'.join(lines) + f'''
}};

static const lv_image_dsc_t WORDMARK_IMG = {{
  {{
    LV_IMAGE_HEADER_MAGIC,
    LV_COLOR_FORMAT_ARGB8888,
    0,
    WORDMARK_IMG_W,
    WORDMARK_IMG_H,
    WORDMARK_IMG_W * 4,
    0,
  }},
  sizeof(WORDMARK_IMG_DATA),
  WORDMARK_IMG_DATA,
  nullptr,
  nullptr,
}};
''')
print(f'{width}x{height}, {len(data)} bytes')
